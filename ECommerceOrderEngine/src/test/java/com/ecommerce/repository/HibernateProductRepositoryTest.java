
package com.ecommerce.repository;

import com.ecommerce.model.Product;

import org.junit.jupiter.api.Test;

import java.math.BigDecimal;
import java.util.Optional;

import static org.junit.jupiter.api.Assertions.*;

class HibernateProductRepositoryTest {

    @Test
    void shouldSaveFindUpdateAndDeleteProduct()
            throws Exception {

        ProductRepository repository =
                new HibernateProductRepository();

        /*
         * =====================================================
         * CREATE PRODUCT
         * =====================================================
         *
         * Product ID is generated by MySQL.
         * Do not manually assign an ID.
         */
        Product product = new Product(
                "Hibernate Test Mouse",
                "Electronics",
                new BigDecimal("39.99"),
                "Wireless mouse for Hibernate CRUD testing",
                "TestBrand"
        );

        Long productId = null;

        try {

            /*
             * =================================================
             * SAVE
             * =================================================
             */
            repository.save(product);

            productId = product.getId();

            assertNotNull(productId);
            assertTrue(productId > 0);

            /*
             * =================================================
             * FIND BY ID
             * =================================================
             */
            Optional<Product> saved =
                    repository.findById(productId);

            assertTrue(saved.isPresent());

            assertEquals(
                    "Hibernate Test Mouse",
                    saved.get().getName()
            );

            assertEquals(
                    "Electronics",
                    saved.get().getCategory()
            );

            assertEquals(
                    39.99,
                    saved.get().getPrice(),
                    0.001
            );

            /*
             * =================================================
             * UPDATE
             * =================================================
             *
             * Load the existing persisted product.
             * Do not create another Product with a fixed ID.
             */
            Product productToUpdate =
                    repository.findById(productId)
                            .orElseThrow();

            productToUpdate.updatePrice(
                    new BigDecimal("49.99")
            );

            repository.update(productToUpdate);

            /*
             * =================================================
             * VERIFY UPDATE
             * =================================================
             */
            Product updated =
                    repository.findById(productId)
                            .orElseThrow();

            assertEquals(
                    49.99,
                    updated.getPrice(),
                    0.001
            );

            /*
             * =================================================
             * DELETE
             * =================================================
             */
            boolean deleted =
                    repository.deleteById(productId);

            assertTrue(deleted);

            /*
             * =================================================
             * VERIFY DELETION
             * =================================================
             */
            assertTrue(
                    repository.findById(productId)
                            .isEmpty()
            );

        } finally {

            /*
             * Cleanup only the product created by this test.
             *
             * If the normal DELETE operation already succeeded,
             * the repository simply returns false.
             */
            if (productId != null) {
                repository.deleteById(productId);
            }
        }
    }
}
