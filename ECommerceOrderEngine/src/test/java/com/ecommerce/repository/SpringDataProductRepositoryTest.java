
package com.ecommerce.repository;

import com.ecommerce.EcommerceApplication;
import com.ecommerce.model.Product;

import org.junit.jupiter.api.Test;

import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.transaction.annotation.Transactional;

import java.math.BigDecimal;
import java.util.List;
import java.util.Optional;

import static org.junit.jupiter.api.Assertions.*;

@SpringBootTest(classes = EcommerceApplication.class)
@Transactional
class SpringDataProductRepositoryTest {

    @Autowired
    private SpringDataProductRepository productRepository;

    @Test
    void shouldPerformProductCrudUsingSpringDataJpa() {

        /*
         * =====================================================
         * CREATE PRODUCT
         * =====================================================
         *
         * Product ID is generated by MySQL.
         * Do not assign an ID manually.
         */
        Product product = new Product(
                "Spring Data Keyboard",
                "Electronics",
                new BigDecimal("99.99"),
                "Mechanical keyboard for repository testing",
                "TestBrand"
        );

        Product saved = productRepository.saveAndFlush(product);

        assertNotNull(saved);
        assertNotNull(saved.getId());
        assertTrue(saved.getId() > 0);

        long productId = saved.getId();

        /*
         * =====================================================
         * READ BY ID
         * =====================================================
         */
        Optional<Product> found =
                productRepository.findById(productId);

        assertTrue(found.isPresent());

        assertEquals(
                "Spring Data Keyboard",
                found.get().getName()
        );

        assertEquals(
                "Electronics",
                found.get().getCategory()
        );

        /*
         * =====================================================
         * READ ALL
         * =====================================================
         */
        List<Product> products =
                productRepository.findAll();

        assertTrue(
                products.stream()
                        .anyMatch(p ->
                                productId == p.getId()
                        )
        );

        /*
         * =====================================================
         * UPDATE PRICE
         * =====================================================
         *
         * Update the existing managed entity.
         * Do not create another Product with a fixed ID.
         */
        Product existing = found.get();

        existing.updatePrice(
                new BigDecimal("129.99")
        );

        productRepository.saveAndFlush(existing);

        /*
         * =====================================================
         * VERIFY UPDATE
         * =====================================================
         */
        Product updated = productRepository
                .findById(productId)
                .orElseThrow();

        assertEquals(
                129.99,
                updated.getPrice(),
                0.001
        );

        /*
         * =====================================================
         * DELETE PRODUCT
         * =====================================================
         */
        productRepository.deleteById(productId);

        productRepository.flush();

        /*
         * =====================================================
         * VERIFY DELETION
         * =====================================================
         */
        assertFalse(
                productRepository.existsById(productId)
        );
    }
}
